// Scans levels/level-*.json and writes a single bundle, levels/all-levels.js,
// that index.html loads with one <script> tag. Run this whenever you add or
// remove a level file from levels/ — no edits to index.html required.
//
// Run: node scripts/build-manifest.js

const fs = require('fs');
const path = require('path');

const LEVELS_DIR = path.join(__dirname, '..', 'levels');
const BUNDLE_PATH = path.join(LEVELS_DIR, 'all-levels.js');

function discoverLevelKeys() {
  return fs.readdirSync(LEVELS_DIR)
    .map(name => name.match(/^(level-(\d+))\.json$/))
    .filter(Boolean)
    .map(m => ({ key: m[1], n: +m[2] }))
    .sort((a, b) => a.n - b.n)
    .map(e => e.key);
}

function buildBundle() {
  const keys = discoverLevelKeys();
  const lines = [
    '// Auto-generated by scripts/build-manifest.js. Do not edit by hand.',
    '// Bundles every levels/level-*.json so index.html can load all levels',
    '// with one <script> tag (necessary for file:// where fetch is blocked).',
    '(function () {',
    '  if (!window.MAHJONG_LEVELS) window.MAHJONG_LEVELS = {};',
  ];
  for (const key of keys) {
    const raw = fs.readFileSync(path.join(LEVELS_DIR, key + '.json'), 'utf8');
    lines.push('  window.MAHJONG_LEVELS[' + JSON.stringify(key) + '] = ' + raw.trim() + ';');
  }
  lines.push('  window.MAHJONG_LEVEL_KEYS = ' + JSON.stringify(keys) + ';');
  lines.push('})();');
  lines.push('');
  fs.writeFileSync(BUNDLE_PATH, lines.join('\n'), 'utf8');
  console.log('Wrote', path.relative(path.join(__dirname, '..'), BUNDLE_PATH),
              'with', keys.length, 'levels:', keys.join(', '));
}

if (require.main === module) buildBundle();
module.exports = { discoverLevelKeys, buildBundle };
